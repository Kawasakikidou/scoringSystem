    /** 初始化：事务内清空全部四维评分/附加分/操作日志，候选人回到未面试（名单保留）。 */
    void resetAll() throws SQLException {
        boolean oldAuto = conn.getAutoCommit();
        conn.setAutoCommit(false);
        try {
            try (Statement st = conn.createStatement()) {
                st.executeUpdate("DELETE FROM op_log");
                st.executeUpdate("DELETE FROM score");
                st.executeUpdate("DELETE FROM bonus");
                st.executeUpdate("UPDATE candidate SET status = 'PENDING', finished_at = NULL");
            }
            conn.commit();
        } catch (SQLException e) {
            conn.rollback();
            throw e;
        } finally {
            conn.setAutoCommit(oldAuto);
        }
    }

    // ------------------------------------------------------------------ 彻底重置（删除一切数据与库文件）

    /** 彻底重置将删除的目标文件（当前存在的）：库文件与伴生文件 + 数据目录下全部 CSV。 */
    List<String> resetTargets() {
        if (!jdbcUrl.startsWith("jdbc:h2:file:")) {
            throw new IllegalStateException("彻底重置仅支持文件型数据库（jdbc:h2:file:…），当前 URL：" + jdbcUrl);
        }
        String base = jdbcUrl.substring("jdbc:h2:file:".length());
        int semi = base.indexOf(';');
        if (semi >= 0) {
            base = base.substring(0, semi);
        }
        File baseFile = new File(base);
        File dir = baseFile.getAbsoluteFile().getParentFile();
        String fileName = baseFile.getName();
        if (dir == null) {
            throw new IllegalStateException("无法定位数据库文件目录：" + base);
        }
        List<String> targets = new ArrayList<>();
        for (String suffix : new String[]{".mv.db", ".trace.db", ".lock.db"}) {
            File f = new File(dir, fileName + suffix);
            if (f.exists()) {
                targets.add(f.getAbsolutePath());
            }
        }
        File[] csvs = dir.listFiles((d, name) -> name.endsWith(".csv"));
        if (csvs != null) {
            for (File f : csvs) {
                targets.add(f.getAbsolutePath());
            }
        }
        return targets;
    }

    /**
     * 彻底重置：关库 → 删除数据库文件及其伴生文件（*.mv.db / *.trace.db / *.lock.db）与
     * 数据目录下全部 CSV 导出/备份 → 原地重建空库。返回已删除文件列表。
     * 仅支持 {@code jdbc:h2:file:} 文件库。
     */
    List<String> resetEverything() {
        List<String> targets = resetTargets();

        // 1) 关闭连接（H2 文件锁随之释放）
        closeQuietly();
        conn = null;

        // 2) 删除目标文件
        List<String> deleted = new ArrayList<>();
        for (String target : targets) {
            if (new File(target).delete()) {
                deleted.add(target);
            }
        }

        // 3) 重建空库
        try {
            conn = DriverManager.getConnection(jdbcUrl, "sa", "");
            migrationNotice = null;
            initSchema();
        } catch (SQLException e) {
            throw new IllegalStateException("彻底重置后重建数据库失败：" + e.getMessage(), e);
        }
        return deleted;
    }

    private void closeQuietly() {
        if (conn != null) {
            try {
                conn.close();
            } catch (SQLException ignored) {
                // 关闭阶段异常无可控处理点；core 层不允许任何控制台输出
            }
        }
    }

    // ------------------------------------------------------------------ 事务

    /** 在事务中执行动作；成功 commit，异常（SQL/运行时）rollback 后原样抛出。 */
    <T> T tx(TxAction<T> action) throws SQLException {
        boolean oldAuto = conn.getAutoCommit();
        conn.setAutoCommit(false);
        try {
            T result = action.run();
            conn.commit();
            return result;
        } catch (SQLException | RuntimeException e) {
            try {
                conn.rollback();
            } catch (SQLException ignored) {
                // 回滚失败无补救路径，保持原始异常
            }
            throw e;
        } finally {
            conn.setAutoCommit(oldAuto);
        }
    }

    @FunctionalInterface
    interface TxAction<T> {
        T run() throws SQLException;
    }

