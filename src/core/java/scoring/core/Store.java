    Optional<LogRow> lastOpLog() throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement(
                "SELECT o.seq, o.student_no, o.op_type, o.ref_id, o.r, o.t, o.s, o.f, o.amount,"
                        + " o.reason, o.occurred_at, o.created_at,"
                        + " c.name FROM op_log o JOIN candidate c ON c.student_no = o.student_no"
                        + " ORDER BY o.seq DESC LIMIT 1")) {
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    return Optional.empty();
                }
                Timestamp occurred = rs.getTimestamp("occurred_at");
                return Optional.of(new LogRow(
                        rs.getLong("seq"),
                        rs.getString("student_no"),
                        rs.getString("name"),
                        rs.getString("op_type"),
                        rs.getLong("ref_id"),
                        rs.getBigDecimal("r"),
                        rs.getBigDecimal("t"),
                        rs.getBigDecimal("s"),
                        rs.getBigDecimal("f"),
                        rs.getBigDecimal("amount"),
                        rs.getString("reason"),
                        occurred == null ? null : occurred.toLocalDateTime(),
                        rs.getTimestamp("created_at").toLocalDateTime()));
            }
        }
    }

