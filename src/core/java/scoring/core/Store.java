    /** 改学号：事务内级联迁移 score/bonus/op_log 后更新主表（调用方已确认新号不存在、非面试中）。 */
    void moveCandidateStudentNo(String oldNo, String newNo) throws SQLException {
        boolean oldAuto = conn.getAutoCommit();
        conn.setAutoCommit(false);
        try {
            for (String table : new String[]{"score", "bonus", "op_log"}) {
                try (PreparedStatement ps = conn.prepareStatement(
                        "UPDATE " + table + " SET student_no = ? WHERE student_no = ?")) {
                    ps.setString(1, newNo);
                    ps.setString(2, oldNo);
                    ps.executeUpdate();
                }
            }
            try (PreparedStatement ps = conn.prepareStatement(
                    "UPDATE candidate SET student_no = ?, updated_at = CURRENT_TIMESTAMP WHERE student_no = ?")) {
                ps.setString(1, newNo);
                ps.setString(2, oldNo);
                ps.executeUpdate();
            }
            conn.commit();
        } catch (SQLException e) {
            try {
                conn.rollback();
            } catch (SQLException ignored) {
                // 保持原始异常
            }
            throw e;
        } finally {
            conn.setAutoCommit(oldAuto);
        }
    }

    /** 删除候选人：事务内级联删除其评分/附加分/操作日志后再删主表行。 */
    void deleteCandidateCascade(String studentNo) throws SQLException {
        boolean oldAuto = conn.getAutoCommit();
        conn.setAutoCommit(false);
        try {
            for (String table : new String[]{"score", "bonus", "op_log"}) {
                try (PreparedStatement ps = conn.prepareStatement(
                        "DELETE FROM " + table + " WHERE student_no = ?")) {
                    ps.setString(1, studentNo);
                    ps.executeUpdate();
                }
            }
            try (PreparedStatement ps = conn.prepareStatement(
                    "DELETE FROM candidate WHERE student_no = ?")) {
                ps.setString(1, studentNo);
                ps.executeUpdate();
            }
            conn.commit();
        } catch (SQLException e) {
            try {
                conn.rollback();
            } catch (SQLException ignored) {
                // 保持原始异常
            }
            throw e;
        } finally {
            conn.setAutoCommit(oldAuto);
        }
    }

