    SystemStats stats() throws SQLException {
        Map<CandidateStatus, Integer> byStatus = new EnumMap<>(CandidateStatus.class);
        int total = 0;
        try (PreparedStatement ps = conn.prepareStatement(
                "SELECT status, COUNT(*) AS c FROM candidate GROUP BY status");
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                CandidateStatus s = CandidateStatus.fromDb(rs.getString("status"));
                byStatus.put(s, rs.getInt("c"));
                total += rs.getInt("c");
            }
        }
        return new SystemStats(
                total,
                byStatus.getOrDefault(CandidateStatus.PENDING, 0),
                byStatus.getOrDefault(CandidateStatus.INTERVIEWING, 0),
                byStatus.getOrDefault(CandidateStatus.FINISHED, 0),
                countRows("score"),
                countRows("bonus"));
    }

